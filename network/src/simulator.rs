#[derive(Deserialize)]
struct Reference {
    files: Vec<Resource>,
}
#[derive(Deserialize)]
struct Resource {
    id: String,
    size: u64,
    sha256: String,
}

fn hash(bytes: impl AsRef<[u8]>) -> String {
    format!("{:x}", Sha256::digest(bytes.as_ref()))
}
fn resource_content(directory: &Path) -> Result<String> {
    let reference: Reference = serde_json::from_str(include_str!("../../config/resources.json"))?;
    let index = rm4_mr_preparation::ResourceIndex::parse(&fs::read_to_string(
        directory.join("DATA/files.tsv"),
    )?)?;
    let mut fingerprints = Vec::new();
    for file in reference.files {
        if !(file.id.ends_with(".MR") || file.id.ends_with(".IMG") || file.id.ends_with(".VAB")) {
            continue;
        }
        index.require(&file.id, file.size)?;
        let path = directory.join(file.id.trim_start_matches('/'));
        let bytes = fs::read(&path)
            .with_context(|| format!("Reading local resource {}", path.display()))?;
        ensure!(
            bytes.len() as u64 == file.size && hash(&bytes) == file.sha256,
            "Local stock resource differs: {}",
            file.id
        );
        if file.id != "/DATA/MENU.MR" {
            fingerprints.push(format!("{}:{}", file.id, file.sha256));
        }
    }
    fingerprints.sort();
    Ok(hash(fingerprints.join("\n")))
}

// Local test tape only. Production builds reject this environment setting.
#[cfg(feature = "rollback_probe")]
#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct Fixture {
    cars: Option<Vec<String>>,
    world: Option<String>,
    projectile_target: Option<String>,
    #[serde(default)]
    actions: Vec<FixtureAction>,
}
#[cfg(feature = "rollback_probe")]
#[derive(Clone, Deserialize, PartialEq, Eq)]
struct FixtureAction {
    tick: u32,
    name: String,
    distance: Option<i32>,
    #[serde(default)]
    args: Vec<i32>,
    until: Option<u32>,
    projectile: Option<String>,
}

fn engine() -> Result<Engine> {
    let mut config = Config::new();
    config.epoch_interruption(true);
    // An image-built module must run on every x86-64 container host, not just its builder CPU.
    #[cfg(all(target_os = "linux", target_arch = "x86_64"))]
    config.target("x86_64-unknown-linux-musl")?;
    Ok(Engine::new(&config)?)
}

pub fn precompile(input: &Path, output: &Path) -> Result<()> {
    let engine = engine()?;
    let bytes = fs::read(input)?;
    fs::write(output, engine.precompile_module(&bytes)?)?;
    fs::write(output.with_extension("sha256"), hash(&bytes))?;
    Ok(())
}

fn load_module(engine: &Engine, bytes: &[u8], cache: Option<&Path>) -> Result<Module> {
    if let Some(cache) = cache {
        ensure!(
            fs::read_to_string(cache.with_extension("sha256"))? == hash(bytes),
            "Precompiled simulation belongs to a different Wasm build"
        );
        // SAFETY: this path is deployment-controlled, generated by this exact binary in the image build.
        // Never deserialize module uploads or any client-provided native code.
        Ok(unsafe { Module::deserialize_file(engine, cache)? })
    } else {
        Ok(Module::new(engine, bytes)?)
    }
}

